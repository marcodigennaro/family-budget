"""A general places tree (world > continent > region > country), from open data.

Nothing here is personal: the tree is generated from Unicode CLDR, the data
behind country names in most operating systems and browsers.

- Containment comes from CLDR's territoryContainment, which follows the
  UN M49 standard (001 world, 150 Europe, 039 Southern Europe, IT Italy).
- Names in each language come from CLDR via the babel library.
- The vocabulary is schema.org, so any RDF tool understands the file:

      place:IT a schema:Country ;
          schema:identifier "IT" ;               # ISO 3166 code
          schema:name "Italy"@en , "Italie"@fr ;
          schema:containedInPlace place:039 .    # Southern Europe

Generate the file once (needs internet and the dev requirements):

    python -m family_budget.places            # downloads CLDR, writes PLACES_PATH
    python -m family_budget.places file.json  # or use a local CLDR file

Reading it later only needs rdflib.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from collections.abc import Iterable
from pathlib import Path

from rdflib import RDF, Graph, Literal, Namespace
from rdflib.term import Node

SCHEMA = Namespace("https://schema.org/")
PLACE = Namespace("https://budget.mdigennaro.net/place/")

CLDR_VERSION = "46.0.0"
CLDR_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr-json/"
    f"{CLDR_VERSION}/cldr-json/cldr-core/supplemental/territoryContainment.json"
)
WORLD = "001"
LANGUAGES = ("en", "fr", "nl", "de", "it", "es", "pt")


# --- building the tree --------------------------------------------------------------


def fetch_containment(url: str = CLDR_URL) -> dict:
    """Download CLDR's territoryContainment (code -> {"_contains": [...]})."""
    with urllib.request.urlopen(url, timeout=30) as response:
        return json.load(response)["supplemental"]["territoryContainment"]


def _parents(containment: dict) -> dict[str, str]:
    """child code -> parent code, keeping only the M49 tree.

    Skipped: groupings that overlap the tree (EU, UN, eurozone, Latin
    America) and old versions of regions ("039-status-deprecated").
    """
    parents = {}
    for parent, entry in containment.items():
        if "-status-" in parent or entry.get("_grouping") == "true":
            continue
        for child in entry["_contains"]:
            parents[child] = parent
    return parents


def build_places(containment: dict, languages: Iterable[str] = LANGUAGES) -> Graph:
    """Turn CLDR containment into a schema.org graph with names in `languages`."""
    from babel import Locale  # only needed to build, not to read

    names = {lang: Locale.parse(lang).territories for lang in languages}
    english = Locale.parse("en").territories
    parents = _parents(containment)

    graph = Graph()
    graph.bind("schema", SCHEMA)
    graph.bind("place", PLACE)

    def known(code: str) -> bool:
        # a place needs a CLDR name and an unbroken chain up to the world
        while code != WORLD:
            if code not in english or code not in parents:
                return False
            code = parents[code]
        return True

    for code in [WORLD, *parents]:
        if not known(code):
            continue
        node = PLACE[code]
        parent = parents.get(code)
        if code.isalpha():
            kind = SCHEMA.Country
        elif parent == WORLD:
            kind = SCHEMA.Continent
        else:
            kind = SCHEMA.Place
        graph.add((node, RDF.type, kind))
        graph.add((node, SCHEMA.identifier, Literal(code)))
        for lang, territory_names in names.items():
            if code in territory_names:
                graph.add(
                    (node, SCHEMA.name, Literal(territory_names[code], lang=lang))
                )
        if parent:
            graph.add((node, SCHEMA.containedInPlace, PLACE[parent]))
    return graph


HEADER = f"""\
# Places tree generated by `python -m family_budget.places`. Do not edit by hand.
# Source: Unicode CLDR {CLDR_VERSION} (territory containment = UN M49; names).
# Data copyright Unicode, Inc., Unicode License v3: https://www.unicode.org/license.txt

"""


def write_places(graph: Graph, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + graph.serialize(format="turtle"), encoding="utf-8")


# --- reading the tree ---------------------------------------------------------------


def load_places(path: Path) -> Graph:
    return Graph().parse(path)


def _node(graph: Graph, code: str) -> Node | None:
    return graph.value(predicate=SCHEMA.identifier, object=Literal(code))


def place_path(graph: Graph, code: str) -> list[str]:
    """'IT' -> ['001', '150', '039', 'IT'] (world first); [] if unknown."""
    path: list[str] = []
    node = _node(graph, code)
    while node is not None:
        path.insert(0, str(graph.value(node, SCHEMA.identifier)))
        node = graph.value(node, SCHEMA.containedInPlace)
    return path


def names_within(graph: Graph, code: str) -> set[str]:
    """Every name of a place and of all places inside it, plus country codes.

    'IT' -> {'IT', 'Italy', 'Italie', ...}. Numeric region codes are left out:
    "005" would match amounts and references in the bank text.
    """
    start = _node(graph, code)
    if start is None:
        raise KeyError(f"no place with code {code!r}")
    found: set[str] = set()
    todo = [start]
    while todo:
        node = todo.pop()
        found |= {str(name) for name in graph.objects(node, SCHEMA.name)}
        identifier = str(graph.value(node, SCHEMA.identifier))
        if identifier.isalpha():
            found.add(identifier)
        todo += list(graph.subjects(SCHEMA.containedInPlace, node))
    return found


def main(argv: list[str]) -> None:
    from family_budget.config import PLACES_PATH

    if argv:
        containment = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
        containment = containment["supplemental"]["territoryContainment"]
    else:
        print(f"Downloading CLDR {CLDR_VERSION} territory containment...")
        containment = fetch_containment()
    graph = build_places(containment)
    write_places(graph, PLACES_PATH)
    countries = len(set(graph.subjects(RDF.type, SCHEMA.Country)))
    print(f"Wrote {countries} countries and their regions to {PLACES_PATH}")


if __name__ == "__main__":
    main(sys.argv[1:])
